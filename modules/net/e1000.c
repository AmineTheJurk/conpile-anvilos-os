/* These IDs are registered for matching, but this legacy descriptor backend is
 * specifically for 8254x-compatible hardware. */
int mod_init(const kmod_api_t* api, const kmod_pci_dev_t* dev) {
    if (!api || !dev || !api->register_net || !api->vmm_map_mmio || !api->pci_enable_busmaster)
        return -1;
    uint32_t bar = dev->bar[0];
    if (!bar || (bar & 1U)) return -1;
    uint32_t mmio_phys = bar & ~0xFU;
    volatile uint32_t* mm = (volatile uint32_t*)api->vmm_map_mmio(mmio_phys, 0x20000);
    if (!mm) return -1;

    /* RAL/RAH are valid only when RAH.AV is set. Never invent a MAC address. */
    uint32_t ral = mm[0x5400 / 4], rah = mm[0x5404 / 4];
    uint8_t mac[6] = {(uint8_t)ral,(uint8_t)(ral >> 8),(uint8_t)(ral >> 16),
                      (uint8_t)(ral >> 24),(uint8_t)rah,(uint8_t)(rah >> 8)};
    if (!(rah & 0x80000000U) || ((mac[0]|mac[1]|mac[2]|mac[3]|mac[4]|mac[5]) == 0))
        return -1;

    api->pci_enable_busmaster(dev->bus, dev->slot, dev->func);
    uint32_t status = mm[0x0008 / 4];
    uint32_t speed_code = (status >> 6) & 3U;
    uint32_t speed = speed_code == 2 ? 1000 : (speed_code == 1 ? 100 : 10);
    api->register_net("e1000", false, mac, (status & (1U << 1)) != 0, speed, mmio_phys);
    return 0;
}
