int mod_init(const kmod_api_t* api, const kmod_pci_dev_t* dev) {
    api->pci_enable_busmaster(dev->bus, dev->slot, dev->func);
    uint32_t vram_phys = dev->bar[0] & ~0xFU;
    uint32_t mmio_phys = dev->bar[2] & ~0xFU;
    if (mmio_phys) api->vmm_map_mmio(mmio_phys, 0x10000);
    api->log("[radeondrm.mod] ATI/AMD Radeon [%04x:%04x] MMIO=0x%08x VRAM=0x%08x\n",
             dev->vendor_id, dev->device_id, mmio_phys, vram_phys);
    api->register_gpu("radeondrm", "AMD Radeon", dev->device_id, mmio_phys ? mmio_phys : vram_phys, 256, "OpenBSD Radeon DRM");
    return 0;
}
