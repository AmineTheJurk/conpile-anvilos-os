int mod_init(const kmod_api_t* api, const kmod_pci_dev_t* dev) {
    api->pci_enable_busmaster(dev->bus, dev->slot, dev->func);
    uint32_t mmio_phys = dev->bar[0] & ~0xFU;
    uint32_t vram_mb = (dev->bar[2] & ~0xFU) ? 256 : 128;
    if (mmio_phys) {
        volatile uint32_t* mm = (volatile uint32_t*)api->vmm_map_mmio(mmio_phys, 0x10000);
        if (mm) {
            uint32_t pipea = mm[0x70008 / 4];
            api->log("[inteldrm.mod] Intel iGPU [%04x:%04x] GTTMMADR=0x%08x PIPEACONF=0x%08x\n",
                     dev->vendor_id, dev->device_id, mmio_phys, pipea);
        }
    }
    api->register_gpu("inteldrm", "Intel iGPU/Arc", dev->device_id, mmio_phys, vram_mb, "OpenBSD i915/Xe DRM");
    return 0;
}
