int mod_init(const kmod_api_t* api, const kmod_pci_dev_t* dev) {
    api->pci_enable_busmaster(dev->bus, dev->slot, dev->func);
    uint32_t vram_phys = dev->bar[0] & ~0xFU;
    uint32_t mmio_phys = dev->bar[5] & ~0xFU;
    if (!mmio_phys) mmio_phys = dev->bar[2] & ~0xFU;
    uint32_t vram_mb = 512;
    if (mmio_phys) {
        volatile uint32_t* mm = (volatile uint32_t*)api->vmm_map_mmio(mmio_phys, 0x10000);
        if (mm) {
            uint32_t memsz = mm[0x5428 / 4];
            if (memsz > 0 && memsz < 0x10000) vram_mb = memsz;
            api->log("[amdgpu.mod] AMD APU/Radeon [%04x:%04x] MMIO=0x%08x VRAM_BAR=0x%08x\n",
                     dev->vendor_id, dev->device_id, mmio_phys, vram_phys);
        }
    }
    api->register_gpu("amdgpu", "AMD Radeon/APU", dev->device_id, mmio_phys ? mmio_phys : vram_phys, vram_mb, "OpenBSD AMDGPU DRM");
    return 0;
}
