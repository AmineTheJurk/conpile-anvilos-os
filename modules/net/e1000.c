int mod_init(const kmod_api_t* api, const kmod_pci_dev_t* dev) {
    api->pci_enable_busmaster(dev->bus, dev->slot, dev->func);

    /* Intel e1000 family exposes the MAC address in the RAL/RAH MMIO registers. */
    uint32_t mmio_phys = dev->bar[0] & ~0xFU;
    uint8_t mac[6] = { 0 };
    bool up = false;
    uint32_t speed_mbps = 1000;

    if (mmio_phys && !(dev->bar[0] & 1)) {
        volatile uint32_t* mm = (volatile uint32_t*)api->vmm_map_mmio(mmio_phys, 0x20000);
        if (mm) {
            uint32_t ral = mm[0x5400 / 4];
            uint32_t rah = mm[0x5404 / 4];
            uint32_t status = mm[0x0008 / 4];

            mac[0] = (uint8_t)(ral & 0xFF);
            mac[1] = (uint8_t)((ral >> 8) & 0xFF);
            mac[2] = (uint8_t)((ral >> 16) & 0xFF);
            mac[3] = (uint8_t)((ral >> 24) & 0xFF);
            mac[4] = (uint8_t)(rah & 0xFF);
            mac[5] = (uint8_t)((rah >> 8) & 0xFF);

            up = (status & 0x01) != 0;
            if ((status >> 5) & 1U) speed_mbps = 1000;
            else if ((status >> 4) & 1U) speed_mbps = 100;
            else speed_mbps = 10;
        }
    }

    if (mac[0] == 0 && mac[1] == 0 && mac[2] == 0 && mac[3] == 0 && mac[4] == 0 && mac[5] == 0) {
        mac[0] = 0x52;
        mac[1] = 0x54;
        mac[2] = 0x00;
        mac[3] = (uint8_t)((dev->vendor_id >> 8) & 0xFF);
        mac[4] = (uint8_t)(dev->device_id & 0xFF);
        mac[5] = (uint8_t)((dev->slot << 1) | dev->func);
    }

    api->register_net("e1000", false, mac, up, speed_mbps, mmio_phys);
    return 0;
}
