int mod_init(const kmod_api_t* api, const kmod_pci_dev_t* dev) {
    api->pci_enable_busmaster(dev->bus, dev->slot, dev->func);
    uint32_t mmio_phys = dev->bar[0] & ~0xFU;
    uint8_t mac[6] = {0};
    bool up = false;
    uint32_t spd = 1000;
    if (mmio_phys && !(dev->bar[0] & 1)) {
        volatile uint32_t* mm = (volatile uint32_t*)api->vmm_map_mmio(mmio_phys, 0x20000);
        if (mm) {
            uint32_t ral = mm[0x5400 / 4];
            uint32_t rah = mm[0x5404 / 4];
            uint32_t st  = mm[0x0008 / 4];
            mac[0] = (uint8_t)(ral & 0xFF);
            mac[1] = (uint8_t)((ral >> 8) & 0xFF);
            mac[2] = (uint8_t)((ral >> 16) & 0xFF);
            mac[3] = (uint8_t)((ral >> 24) & 0xFF);
            mac[4] = (uint8_t)(rah & 0xFF);
            mac[5] = (uint8_t)((rah >> 8) & 0xFF);
            up = (st & 0x02) != 0;
            uint32_t sp = (st >> 6) & 0x03;
            spd = (sp == 2) ? 1000 : ((sp == 1) ? 100 : 10);
        }
    }
    api->register_net("em", false, mac, up, spd, mmio_phys);
    return 0;
}
