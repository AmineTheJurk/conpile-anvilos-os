bool fb_init(const boot_info_t* bi) {
    if (!bi->vbe_active || bi->fb_addr == 0 || bi->fb_bpp != 32) {
        g_active = false;
        return false;
    }

    g_width    = bi->fb_width;
    g_height   = bi->fb_height;
    g_pitch_px = bi->fb_pitch / 4;
    fb_hw      = (uint32_t*)bi->fb_addr;

    fb_back = (uint32_t*)kmalloc(g_width * g_height * 4);
    if (!fb_back) {
        serial_puts("[FB] Backbuffer alloc failed\n");
        g_active = false;
        return false;
    }
    memset(fb_back, 0, g_width * g_height * 4);
    g_active = true;
    return true;
}

bool     fb_is_active(void) { return g_active; }
uint32_t fb_width(void)     { return g_width; }
uint32_t fb_height(void)    { return g_height; }

void fb_put_pixel(int32_t x, int32_t y, uint32_t color) {
    if (!g_active) return;
    if (x < 0 || y < 0 || (uint32_t)x >= g_width || (uint32_t)y >= g_height) return;
    fb_back[(uint32_t)y * g_width + (uint32_t)x] = color;
}

void fb_fill_rect(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t color) {
    if (!g_active || w <= 0 || h <= 0) return;
    int32_t x0 = x < 0 ? 0 : x;
    int32_t y0 = y < 0 ? 0 : y;
    int32_t x1 = (x + w) > (int32_t)g_width  ? (int32_t)g_width  : (x + w);
    int32_t y1 = (y + h) > (int32_t)g_height ? (int32_t)g_height : (y + h);

    for (int32_t py = y0; py < y1; py++) {
        uint32_t* row = &fb_back[(uint32_t)py * g_width];
        for (int32_t px = x0; px < x1; px++) {
            row[px] = color;
        }
    }
}

void fb_draw_rect(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t color) {
    fb_fill_rect(x, y, w, 1, color);
    fb_fill_rect(x, y + h - 1, w, 1, color);
    fb_fill_rect(x, y, 1, h, color);
    fb_fill_rect(x + w - 1, y, 1, h, color);
}

void fb_fill_gradient_v(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t top_col, uint32_t bot_col) {
    if (!g_active || w <= 0 || h <= 0) return;
    uint8_t r0 = (top_col >> 16) & 0xFF, g0 = (top_col >> 8) & 0xFF, b0 = top_col & 0xFF;
    uint8_t r1 = (bot_col >> 16) & 0xFF, g1 = (bot_col >> 8) & 0xFF, b1 = bot_col & 0xFF;

    for (int32_t i = 0; i < h; i++) {
        uint8_t r = (uint8_t)(r0 + ((int32_t)(r1 - r0) * i) / h);
        uint8_t g = (uint8_t)(g0 + ((int32_t)(g1 - g0) * i) / h);
        uint8_t b = (uint8_t)(b0 + ((int32_t)(b1 - b0) * i) / h);
        fb_fill_rect(x, y + i, w, 1, RGB(r, g, b));
    }
}

void fb_draw_char(int32_t x, int32_t y, char c, uint32_t fg, uint32_t bg, bool transparent_bg) {
    if (!g_active) return;
    uint8_t uc = (uint8_t)c;
    if (uc < 0x20 || uc > 0x7E) uc = '?';
    const uint8_t* glyph = font8x8[uc - 0x20];

    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                fb_put_pixel(x + col, y + row, fg);
            } else if (!transparent_bg) {
                fb_put_pixel(x + col, y + row, bg);
            }
        }
    }
}

void fb_draw_string(int32_t x, int32_t y, const char* s, uint32_t fg, uint32_t bg, bool transparent_bg) {
    if (!s) return;
    int32_t cx = x;
    while (*s) {
        if (*s == '\n') {
            y += 12;
            cx = x;
        } else {
            fb_draw_char(cx, y, *s, fg, bg, transparent_bg);
            cx += 8;
        }
        s++;
    }
}

void fb_draw_bitmap_16x16(int32_t x, int32_t y, const uint16_t* rows, uint32_t fg, int scale) {
    if (!g_active || !rows) return;
    if (scale < 1) scale = 1;
    for (int r = 0; r < 16; r++) {
        uint16_t bits = rows[r];
        for (int c = 0; c < 16; c++) {
            if (bits & (0x8000 >> c)) {
                if (scale == 1) {
                    fb_put_pixel(x + c, y + r, fg);
                } else {
                    fb_fill_rect(x + c * scale, y + r * scale, scale, scale, fg);
                }
            }
        }
    }
}

void fb_draw_line(int32_t x0, int32_t y0, int32_t x1, int32_t y1, uint32_t color) {
    if (!g_active) return;
    int32_t dx = x1 > x0 ? x1 - x0 : x0 - x1;
    int32_t sx = x0 < x1 ? 1 : -1;
    int32_t dy = y1 > y0 ? -(y1 - y0) : -(y0 - y1);
    int32_t sy = y0 < y1 ? 1 : -1;
    int32_t err = dx + dy;
    for (;;) {
        fb_put_pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int32_t e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void fb_draw_argb_icon(int32_t x, int32_t y, int32_t w, int32_t h, const uint32_t* argb) {
    if (!g_active || !argb) return;
    for (int32_t row = 0; row < h; row++) {
        int32_t py = y + row;
        if (py < 0 || (uint32_t)py >= g_height) continue;
        for (int32_t col = 0; col < w; col++) {
            int32_t px = x + col;
            if (px < 0 || (uint32_t)px >= g_width) continue;
            uint32_t src = argb[row * w + col];
            uint32_t a = (src >> 24) & 0xFF;
            if (a == 0) continue;
            if (a >= 250) {
                fb_back[(uint32_t)py * g_width + (uint32_t)px] = src & 0x00FFFFFF;
            } else {
                uint32_t dst = fb_back[(uint32_t)py * g_width + (uint32_t)px];
                uint32_t inv = 255 - a;
                uint32_t r = (((src >> 16) & 0xFF) * a + ((dst >> 16) & 0xFF) * inv) >> 8;
                uint32_t g = (((src >> 8) & 0xFF) * a + ((dst >> 8) & 0xFF) * inv) >> 8;
                uint32_t b = ((src & 0xFF) * a + (dst & 0xFF) * inv) >> 8;
                fb_back[(uint32_t)py * g_width + (uint32_t)px] = RGB(r, g, b);
            }
        }
    }
}

void fb_blit_rect(int32_t x, int32_t y, int32_t w, int32_t h, const uint32_t* src, int32_t src_stride) {
    if (!g_active || !src || w <= 0 || h <= 0) return;
    for (int32_t row = 0; row < h; row++) {
        int32_t py = y + row;
        if (py < 0 || (uint32_t)py >= g_height) continue;
        int32_t x0 = x < 0 ? -x : 0;
        int32_t x1 = (x + w > (int32_t)g_width) ? ((int32_t)g_width - x) : w;
        if (x1 <= x0) continue;
        memcpy(&fb_back[(uint32_t)py * g_width + (uint32_t)(x + x0)],
               &src[row * src_stride + x0],
               (size_t)(x1 - x0) * 4);
    }
}

void fb_present(void) {
    if (!g_active || !fb_hw || !fb_back) return;
    if (g_pitch_px == g_width) {
        memcpy(fb_hw, fb_back, g_width * g_height * 4);
    } else {
        for (uint32_t y = 0; y < g_height; y++) {
            memcpy(&fb_hw[y * g_pitch_px], &fb_back[y * g_width], g_width * 4);
        }
    }
}
